"""Stylized ingest: per-clip style resolution, profile ('stylized' vs 'live') quality filters on synthetic stylized
clips (flat colour shapes, frames held on 2s/3s), style counts in dataset.json / manifest."""
import json
import shutil
import subprocess

import numpy as np
import pytest

from nivra.data.ingest import IngestError, IngestOptions, ingest_folder, inspect_dataset
from nivra.data.ingest.pipeline import LIVE_SCENE_THRESHOLD, STYLIZED_SCENE_THRESHOLD, resolve_style
from nivra.data.ingest.quality import QualityLimits, quality_reject, quality_stats
from nivra.data.shards import ShardDataset, read_manifest, style_counts

needs_ff = pytest.mark.skipif(shutil.which("ffmpeg") is None or shutil.which("ffprobe") is None, reason="ffmpeg missing")

PROV = {"source": "synthetic numpy shapes", "license": "CC0-1.0",
        "license_url": "https://creativecommons.org/publicdomain/zero/1.0/",
        "permission": "generated by the test-suite", "collected": "2026-01-01", "contains_people": False,
        "consent": "n/a"}


def shape_clip(T=17, H=256, W=448, hold=2, size=40, bg=(40, 60, 200), fg=(255, 255, 255), step=6):
    """Flat colour background, one flat square that moves every `hold` frames (animation on 2s / 3s)."""
    v = np.empty((T, H, W, 3), np.uint8)
    v[:] = bg
    for t in range(T):
        x = 20 + step * (t // hold) * hold
        v[t, 100:100 + size, x:x + size] = fg
    return v


# ------------------------------------------------------------------ quality filters (no ffmpeg needed)
def test_profiles_live_is_the_original_thresholds():
    live = QualityLimits.for_profile("live")
    assert live == QualityLimits()
    assert (live.min_motion, live.min_contrast, live.min_motion_active, live.min_active_fraction) == (0.35, 4.0, 0.0, 0.0)
    with pytest.raises(ValueError):
        QualityLimits.for_profile("anime")


def test_stylized_keeps_held_frames_live_rejects():
    clip = shape_clip(hold=3, size=10)          # small flat shape moving on threes: mean frame diff is tiny
    st = quality_stats(clip)
    assert st["active_fraction"] == pytest.approx(0.3125) and st["motion"] < 0.35
    assert quality_reject(st, QualityLimits.for_profile("live")) == "static"
    assert quality_reject(st, QualityLimits.for_profile("stylized")) is None


def test_stylized_keeps_large_flat_areas():
    # a nearly single-colour clip (luma std < 4) with one moving flat shape: "flat" by live-action rules
    clip = shape_clip(hold=1, size=40, bg=(118, 118, 118), fg=(145, 145, 145), step=24)
    st = quality_stats(clip)
    assert st["contrast"] < 4.0
    assert quality_reject(st, QualityLimits.for_profile("live")) == "flat"
    assert quality_reject(st, QualityLimits.for_profile("stylized")) is None


@pytest.mark.parametrize("profile", ["stylized", "live"])
def test_truly_degenerate_clips_rejected_by_both(profile):
    lim = QualityLimits.for_profile(profile)
    assert quality_reject(quality_stats(np.full((17, 256, 448, 3), 90, np.uint8)), lim) == "flat"
    assert quality_reject(quality_stats(np.zeros((17, 256, 448, 3), np.uint8)), lim) == "black"
    assert quality_reject(quality_stats(np.full((17, 256, 448, 3), 255, np.uint8)), lim) == "too_bright"
    still = np.repeat(shape_clip(hold=1)[:1], 17, 0)                    # whole clip static
    assert quality_reject(quality_stats(still), lim) == "static"
    one_change = np.repeat(shape_clip(hold=1)[:1], 17, 0)
    one_change[9:] = shape_clip(hold=1)[5:6]                            # a single pose change in 16 frame pairs
    assert quality_reject(quality_stats(one_change), lim) == "static"


def test_busy_clip_kept_by_both():
    st = quality_stats(shape_clip(hold=1, size=60))
    assert quality_reject(st, QualityLimits.for_profile("live")) is None
    assert quality_reject(st, QualityLimits.for_profile("stylized")) is None


def test_scene_threshold_by_profile():
    assert IngestOptions().resolved_scene_threshold() == STYLIZED_SCENE_THRESHOLD
    assert IngestOptions(profile="live").resolved_scene_threshold() == LIVE_SCENE_THRESHOLD == 0.3
    assert IngestOptions(scene_threshold=0.5).resolved_scene_threshold() == 0.5
    assert IngestOptions(scene_threshold=None).resolved_scene_threshold() is None
    assert IngestOptions().profile == "stylized"


# ------------------------------------------------------------------ style resolution
def test_resolve_style_order():
    prov = {"style": "cartoon"}
    assert resolve_style("anime style. A girl runs.", "3d animation", prov, "pixel art") == ("anime", "A girl runs.")
    assert resolve_style("A girl runs.", "3d animation", prov, "pixel art") == ("3d animation", "A girl runs.")
    assert resolve_style("A girl runs.", None, prov, "pixel art") == ("cartoon", "A girl runs.")
    assert resolve_style("A girl runs.", None, {}, "pixel art") == ("pixel art", "A girl runs.")
    assert resolve_style("A girl runs.", None, {}, "Hand-Drawn") == ("2d animation", "A girl runs.")
    assert resolve_style("A girl runs.", None, {}, None) == ("unspecified", "A girl runs.")
    assert resolve_style("anime fans cheer", None, {}, None) == ("unspecified", "anime fans cheer")


def test_style_counts_helper():
    assert style_counts([{"style": "anime"}, {"style": "anime"}, {}, {"style": "unspecified"}]) == {
        "anime": 2, "unspecified": 2}


# ------------------------------------------------------------------ end to end (ffmpeg)
def _encode(path, frames, fps=24):
    T, H, W, _ = frames.shape
    r = subprocess.run(["ffmpeg", "-hide_banner", "-nostdin", "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgb24",
                        "-s", f"{W}x{H}", "-r", str(fps), "-i", "-", "-pix_fmt", "yuv420p", "-c:v", "libx264",
                        "-preset", "ultrafast", "-crf", "12", str(path)], input=frames.tobytes(), capture_output=True)
    assert r.returncode == 0, r.stderr.decode()


@pytest.fixture(scope="module")
def folder(tmp_path_factory):
    d = tmp_path_factory.mktemp("stylized_videos")

    def three_s(hold, size, **kw):                  # 3 s @ 24 fps
        return np.concatenate([shape_clip(T=24, H=360, W=640, hold=hold, size=size, **kw)] * 3)

    _encode(d / "a_lead.mp4", three_s(3, 14))                      # caption starts with "anime style."
    _encode(d / "b_jsonl.mp4", three_s(3, 14, bg=(200, 60, 40)))   # style from captions.jsonl
    _encode(d / "c_prov.mp4", three_s(2, 24, bg=(40, 160, 60)))    # falls to PROVENANCE.json style / default
    _encode(d / "d_static.mp4", np.repeat(shape_clip(T=1, H=360, W=640, hold=1)[:1], 72, 0))
    (d / "a_lead.txt").write_text("anime style. A white square hops.", encoding="utf-8")
    (d / "b_jsonl.txt").write_text("A square hops on a red field.", encoding="utf-8")
    (d / "c_prov.txt").write_text("A square hops on a green field.", encoding="utf-8")
    (d / "d_static.txt").write_text("nothing happens", encoding="utf-8")
    (d / "captions.jsonl").write_text(
        json.dumps({"file": "b_jsonl.mp4", "caption": "ignored (txt wins)", "style": "3D render"}) + "\n", encoding="utf-8")
    (d / "PROVENANCE.json").write_text(json.dumps(dict(PROV, style="cartoon")), encoding="utf-8")
    return d


def _run(folder, out, **kw):
    kw.setdefault("val_fraction", 0.0)
    kw.setdefault("fps", 24)
    kw.setdefault("scene_threshold", None)
    kw.setdefault("dedup_bits", -1.0)      # dHash ignores colour: the flat test clips would all be duplicates
    return ingest_folder(folder, out, IngestOptions(**kw), log=lambda *_: None)


@needs_ff
def test_stylized_ingest_styles_and_filters(folder, tmp_path):
    s = _run(folder, tmp_path / "st")
    rows = read_manifest(tmp_path / "st")
    by = {}
    for r in rows:
        by.setdefault(r["source_file"], set()).add(r["style"])
    assert by["a_lead.mp4"] == {"anime"} and by["b_jsonl.mp4"] == {"3d animation"} and by["c_prov.mp4"] == {"cartoon"}
    assert "d_static.mp4" not in by and s["rejected"].get("static", 0) >= 1
    lead = next(r for r in rows if r["source_file"] == "a_lead.mp4")
    assert lead["caption"] == "A white square hops."           # leading style phrase moved into the style field
    expect = {}
    for r in rows:
        expect[r["style"]] = expect.get(r["style"], 0) + 1
    assert s["profile"] == "stylized" and s["styles"] == dict(sorted(expect.items()))
    assert sum(s["styles"].values()) == s["clips"] == len(rows) > 0
    assert json.loads((tmp_path / "st" / "dataset.json").read_text(encoding="utf-8"))["styles"] == s["styles"]
    assert ShardDataset(tmp_path / "st", split=None).styles == s["styles"]
    assert inspect_dataset(tmp_path / "st")["per_style"] == s["styles"]
    assert all("motion_active" in r["quality"] for r in rows)


@needs_ff
def test_live_profile_rejects_held_frame_clips(folder, tmp_path):
    live = _run(folder, tmp_path / "live", profile="live")
    sty = _run(folder, tmp_path / "sty")
    assert live["profile"] == "live" and live["options"]["quality"]["min_motion"] == 0.35
    assert live["options"]["quality"]["min_contrast"] == 4.0
    assert sty["options"]["quality"]["min_contrast"] == 1.0
    assert live["clips"] < sty["clips"], (live["rejected"], sty["rejected"])
    assert live["rejected"].get("static", 0) > sty["rejected"].get("static", 0)


@needs_ff
def test_default_style_and_unspecified(folder, tmp_path):
    bare = tmp_path / "bare"
    shutil.copytree(folder, bare)
    (bare / "PROVENANCE.json").write_text(json.dumps(PROV), encoding="utf-8")       # no provenance style
    s = _run(bare, tmp_path / "def", default_style="pixel art")
    assert s["styles"].get("pixel art", 0) > 0 and "cartoon" not in s["styles"]
    s2 = _run(bare, tmp_path / "unspec")
    assert s2["styles"].get("unspecified", 0) > 0
    assert {r["style"] for r in read_manifest(tmp_path / "unspec")} == {"anime", "3d animation", "unspecified"}


@needs_ff
def test_bad_style_inputs_refused(folder, tmp_path):
    with pytest.raises(IngestError, match="default_style"):
        _run(folder, tmp_path / "o1", default_style="banana")
    assert not (tmp_path / "o1").exists()
    with pytest.raises(IngestError, match="profile"):
        _run(folder, tmp_path / "o2", profile="cinema")
    bad = tmp_path / "bad"
    shutil.copytree(folder, bad)
    (bad / "PROVENANCE.json").write_text(json.dumps(dict(PROV, style="banana")), encoding="utf-8")
    with pytest.raises(IngestError, match="style"):
        _run(bad, tmp_path / "o3")
    (bad / "PROVENANCE.json").write_text(json.dumps(PROV), encoding="utf-8")
    (bad / "captions.jsonl").write_text(
        json.dumps({"file": "a_lead.mp4", "caption": "x", "style": "banana"}) + "\n", encoding="utf-8")
    with pytest.raises(IngestError, match="captions.jsonl:1"):
        _run(bad, tmp_path / "o4")
